#!/usr/bin/env python3
"""Install the approved B2 icon exports; never redraw or redesign them.

Canonical sources and approved raster exports live in resources/brand/.
Uses only Python's standard library. Run from any working directory.
Outputs the app icon/ICNS, native tray assets, and SVG geometry for React.
"""
from pathlib import Path
import json
import shutil
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'resources/brand'
NS = {'svg': 'http://www.w3.org/2000/svg'}


def mark(name):
    svg = ET.parse(SOURCE / name).getroot()
    group = svg.find('svg:g', NS)
    if group is None:
        raise ValueError(f'{name}: missing SVG group')
    path = group.find('svg:path', NS)
    if path is None:
        raise ValueError(f'{name}: missing SVG path')
    return {'viewBox': svg.attrib['viewBox'],
            'transform': group.attrib['transform'],
            'path': path.attrib['d']}


def main():
    copies = {
        'app-1024.png': ['build/icon.png', 'resources/icon.png'],
        'app.icns': ['build/icon.icns'],
        'mark-16.png': ['resources/tray/trayTemplate.png'],
        'mark-32.png': ['resources/tray/trayTemplate@2x.png'],
        'app-32.png': ['resources/tray/tray.png'],
    }
    for source, targets in copies.items():
        for target in targets:
            destination = ROOT / target
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(SOURCE / source, destination)
            print('wrote', target)
    module = '// Generated by scripts/generate-icons.py from the approved B2 SVGs.\n'
    for name, filename in [('B2_MARK', 'mark.svg'), ('B2_SMALL_MARK', 'small-mark.svg')]:
        module += f'export const {name} = ' + json.dumps(mark(filename), ensure_ascii=False, indent=2) + ' as const\n'
    (ROOT / 'src/renderer/src/shared/brand-mark.ts').write_text(module)
    print('wrote src/renderer/src/shared/brand-mark.ts')


if __name__ == '__main__':
    main()
