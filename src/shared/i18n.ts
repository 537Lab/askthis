export const dictionaries: Record<UiLocale, Record<string, string>> = {
  'zh-CN': zh,
  'en-US': en
}

export function t(
  locale: UiLocale,
  key: string,
  vars?: Record<string, string | number>
): string {
  let s = dictionaries[locale]?.[key] ?? dictionaries['zh-CN'][key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

export function resolveLocale(pref: string, systemLocale: string): UiLocale {
  if (pref === 'zh-CN' || pref === 'en-US') return pref
  return systemLocale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}
